function resetAturanDigit($conn, $data)
{
    try {
        // 1. Matikan Foreign Key Check & Lakukan TRUNCATE
        mysqli_query($conn, "SET FOREIGN_KEY_CHECKS = 0;");

        $truncateQuery = "TRUNCATE TABLE aturan_digit";
        if (!mysqli_query($conn, $truncateQuery)) {
            throw new Exception("Gagal melakukan TRUNCATE: " . mysqli_error($conn));
        }

        // Aktifkan kembali Foreign Key Check
        mysqli_query($conn, "SET FOREIGN_KEY_CHECKS = 1;");

        // 2. Susun Single Multi-Insert Query
        $values = [];
        foreach ($data as $row) {
            $kode = mysqli_real_escape_string($conn, $row[0] ?? '');

            // Pemetaan param_d6 sampai param_d15 (otomatis terisi NULL jika index tidak tersedia)
            $param_d6  = isset($row[1])  ? "'" . mysqli_real_escape_string($conn, $row[1])  . "'" : "NULL";
