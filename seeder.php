function prosesAturanDigit($aturan_digit)
{
    $counts = [];
    $duplicates = [];

    foreach ($aturan_digit as $index => $row) {
        $kode = $row[0] ?? null;
        if ($kode !== null) {
            if (!isset($counts[$kode])) {
                $counts[$kode] = [];
            }
            $counts[$kode][] = $index;
        }
    }

    foreach ($counts as $kode => $indexes) {
        if (count($indexes) > 1) {
            $duplicates[$kode] = $indexes;
        }
    }

    if (!empty($duplicates)) {
        echo "<h3>Ditemukan Kode Duplikat!</h3>";
        echo "<ul>";
        foreach ($duplicates as $kode => $indexes) {
            $baris = array_map(function ($i) {
                return $i + 1;
            }, $indexes); // Baris ke-1, 2, dst.
            echo "<li>Kode <b>'$kode'</b> muncul sebanyak <b>" . count($indexes) . "x</b> pada baris ke: " . implode(', ', $baris) . "</li>";
        }
        echo "</ul>";
    } else {
        echo "<pre>";
        echo "Tidak ada kode duplikat dalam array.";
        echo "</pre>";
    }
}

function resetKelompokUtama($conn, $data)
{
    try {
        // 1. Matikan Foreign Key Check & Lakukan TRUNCATE
        mysqli_query($conn, "SET FOREIGN_KEY_CHECKS = 0;");

        $truncateQuery = "TRUNCATE TABLE kelompok_utama";
        if (!mysqli_query($conn, $truncateQuery)) {
            throw new Exception("Gagal melakukan TRUNCATE: " . mysqli_error($conn));
        }

        // Aktifkan kembali Foreign Key Check
        mysqli_query($conn, "SET FOREIGN_KEY_CHECKS = 1;");

        // 2. Susun Single Multi-Insert Query
        $values = [];
        foreach ($data as $row) {
            // Mengakses elemen array berdasarkan indeks angka [0, 1, 2]
            $kode        = mysqli_real_escape_string($conn, $row[0] ?? '');
            $keterangan  = mysqli_real_escape_string($conn, $row[1] ?? '');
            $nama_barang = mysqli_real_escape_string($conn, $row[2] ?? '');

            $values[] = "('$kode', '$keterangan', '$nama_barang')";
        }

        if (!empty($values)) {
            $insertQuery = "INSERT INTO kelompok_utama (kode, keterangan, nama_barang) VALUES " . implode(', ', $values);

            if (mysqli_query($conn, $insertQuery)) {
                echo "<b>Berhasil!</b> Tabel <code>kelompok_utama</code> telah dikosongkan dan diisi ulang dengan " . count($values) . " data baru.";
                return true;
            } else {
                throw new Exception("Gagal insert data: " . mysqli_error($conn));
            }
        }

        return false;
    } catch (Exception $e) {
        // Memastikan FK Check selalu diaktifkan kembali jika terjadi error
        mysqli_query($conn, "SET FOREIGN_KEY_CHECKS = 1;");
        echo "<b>Error:</b> " . $e->getMessage();
        return false;
    }
}

